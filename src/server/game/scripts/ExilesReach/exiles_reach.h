static void StartPrivateConversation(Player* player, uint32 conversationId, std::vector<Creature*> actors)
{
    Conversation* conversation = Conversation::CreateConversation(conversationId, player, *player, player->GetGUID(), nullptr, false);
    if (!conversation)
    {
        TC_LOG_DEBUG("scripts", "ExilesReach: failed to create conversation {} for player {}", conversationId, player->GetName());
        return;
    }

    int8 actorId = 0;
    for (Creature* actor : actors)
    {
        conversation->AddActor(actorId, actorId, actor->GetGUID());
        actorId++;
    }

    conversation->Start();
}

static void AddCreditForQuestObjective(Player* player, uint32 questId, int32 objectiveId)
{
    if (player->GetQuestStatus(questId) == QUEST_STATUS_INCOMPLETE)
    {
        if (Quest const* quest = sObjectMgr->GetQuestTemplate(questId))
        {
            for (QuestObjective const& obj : quest->GetObjectives())
            {
                if (obj.ObjectID == objectiveId)
                {
                    uint16 slot = player->FindQuestSlot(questId);
                    if (!player->IsQuestObjectiveComplete(slot, quest, obj)) // just complete once
                    {
                        player->SetQuestObjectiveData(obj, 1);
                        player->SendQuestUpdateAddCredit(quest, ObjectGuid::Empty, obj, 1);
                    }
                }
            }
        }
    }
}

static void CancelExilesReachSceneAuras(Player* player)
{
    if (player->HasAura(SPELL_RITUAL_SCENE_HARPY_BEAM))
        player->RemoveAura(SPELL_RITUAL_SCENE_HARPY_BEAM);

    if (player->HasAura(SPELL_RITUAL_SCENE_HRUN_BEAM))
        player->RemoveAura(SPELL_RITUAL_SCENE_HRUN_BEAM);

    if (player->HasAura(SPELL_RITUAL_SCENE_OGRE_CITADEL))
        player->RemoveAura(SPELL_RITUAL_SCENE_OGRE_CITADEL);

    if (player->HasAura(SPELL_RITUAL_SCENE_MAIN_BEAM))
        player->RemoveAura(SPELL_RITUAL_SCENE_MAIN_BEAM);

    if (player->HasAura(SPELL_AMBIENCE_SCENE))
        player->RemoveAura(SPELL_AMBIENCE_SCENE);
}
